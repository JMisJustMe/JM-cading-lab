def list_tools():
    recipe_schema={'type':'object','additionalProperties':True,'description':'A JM Workshop recipe (validated by the server; see workshop://recipe/example)'}
    donor={'type':'object','required':['name','route','purpose'],'additionalProperties':False,
           'properties':{'name':{'type':'string'},'route':{'type':'string'},'purpose':{'type':'string'}}}
    specs=[]
    for k,(description,required) in TOOLS.items():
        properties={'recipe':recipe_schema,'ancestor':recipe_schema,'candidate':recipe_schema,
                    'donor':donor,'arguments':{'type':'object','description':'Input parameters for the declared recipe'},'cases':{'type':'array','minItems':1,'maxItems':16,'items':{'type':'object'}}}
        specs.append({'name':k,'description':description,'inputSchema':{'type':'object',
            'properties':{p:properties[p] for p in required}, 'required':list(required), 'additionalProperties':False},
            'annotations':{'readOnlyHint':True,'destructiveHint':False,'idempotentHint':True,'openWorldHint':False}})
    return specs

