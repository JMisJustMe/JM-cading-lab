import assert from 'node:assert/strict';
import fs from 'node:fs';
import {GameForgeSpaces} from '../coding-estate/integration/gameforge-spaces.mjs';
import {buildConnectedCarrier} from '../scripts/build_gameforge_connected_carrier.mjs';
import {readWorldBoot,validateWorldSnapshot} from '../coding-estate/integration/gameforge-world-carrier.mjs';
const world={spaces:3,body:'burning',hazards:5,targetX:700,entered:true};
const m=GameForgeSpaces(world),s=m.create();
assert.deepEqual(m.rooms.map(r=>r.body),['burning','humanimals','tboys']);
assert.equal(m.interact(s,{x:850,y:285}).kind,'locked');assert.equal(s.active,0);
assert.equal(m.interact(s,{x:210,y:130}).kind,'collect');
assert.equal(m.interact(s,{x:120,y:285}).kind,'none');
assert.equal(m.interact(s,{x:850,y:285}).kind,'transition');assert.equal(s.active,1);
assert.deepEqual(s.collected,['key-0']);assert.deepEqual(s.opened,['0-1']);
assert.equal(m.interact(s,{x:50,y:285}).kind,'transition');assert.equal(s.active,0);
assert.deepEqual(s.collected,['key-0']);assert.equal(s.transitions,2);
const wall=m.rooms[0].walls[0];
const pos=m.resolve(m.rooms[0],{x:wall.x-30,y:300},{x:wall.x+100,y:300},24);
assert.ok(pos.x<=wall.x-24);assert.equal(pos.y,300);
assert.equal(m.free(m.rooms[0],500,300),true);
assert.throws(()=>m.validate({...s,active:9},false),/SPACES_SESSION_HOLD/);
assert.throws(()=>m.validate({...s,collected:[]},false),/SPACES_DOOR_AUTHORITY_HOLD/);
assert.throws(()=>m.validate({...s,opened:['0-2']},false),/SPACES_PROGRESSION_HOLD/);
const proof=await buildConnectedCarrier('/tmp/jm-connected-source-test');
const html=fs.readFileSync('/tmp/jm-connected-source-test/index.html','utf8');
assert.equal(readWorldBoot(html).world.spaces,3);assert.match(html,/window.GF=GF/);assert.match(html,/installGameForgeSpaces/);
assert.throws(()=>validateWorldSnapshot({...s,rooms:[]},world),/SPACES_MEMORY_HOLD/);
console.log(JSON.stringify({state:'CONNECTED_SPACES_SOURCE_PASS',doorsRequireContactAndKey:true,roundTripState:true,solidCollision:true,invalidStateHold:true,carrierSHA256:proof.sha256,browserProof:false}));
