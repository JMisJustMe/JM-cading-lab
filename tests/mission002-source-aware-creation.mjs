import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {executeSourceAwareCreation} from '../coding-estate/integration/source-aware-creation.mjs';
import {NATIVE_CONNECTED_WORLD_EXAMPLE} from '../navigator/estate-integration/execution-lanes.mjs';
const m=JSON.parse(fs.readFileSync('coding-estate/integration/REGISTRY.json'));
const registry={...m,bodies:m.parts.flatMap(p=>JSON.parse(fs.readFileSync('coding-estate/integration/'+p)).bodies)};
const bind=content=>({identity:'PR395 / recovered connected-world native source',content,sha256:createHash('sha256').update(content).digest('hex')});
const original=bind(NATIVE_CONNECTED_WORLD_EXAMPLE),before=structuredClone(original);
const result=await executeSourceAwareCreation(original,registry);
assert.deepEqual(original,before);
assert.equal(result.source.sha256,original.sha256);
assert.equal(result.execution.state,'WORLD_RECEIVER_EXECUTED_RENDER_PENDING');
assert.equal(result.execution.result.receiver.world.body,'burning');
assert.equal(result.execution.result.receiver.world.spaces,3);
assert.ok(Object.values(result.execution.result.receiver.receipts).every(Boolean));
await assert.rejects(()=>executeSourceAwareCreation({...original,content:original.content+' '},registry),/SOURCE_HASH_HOLD/);
await assert.rejects(()=>executeSourceAwareCreation({...original,sha256:'bad'},registry),/CONTRACT_HOLD/);
await assert.rejects(()=>executeSourceAwareCreation({...original,content:7},registry));
const second=await executeSourceAwareCreation(bind(original.content.replaceAll('burning','humanimals')),registry);
assert.equal(second.execution.result.receiver.world.body,'humanimals');
assert.notEqual(result.source.sha256,second.source.sha256);
assert.notDeepEqual(result.execution.result.receiver.world,second.execution.result.receiver.world);
console.log(JSON.stringify({status:'PASS',checks:12,sourceHashRejection:true,typedSource:true,actualNativeReceiverMutation:true,distinctAuthoredWorlds:true,rendering:'SEPARATE_GATE',historicalFoundationRecovery:false}));
const {executePublicCatalogueSource}=await import('../coding-estate/integration/source-aware-creation.mjs');
const text=fs.readFileSync('lyrics/catalogue-public.json','utf8');
const selected={identity:'lyrics/catalogue-public.json / public source v1.2',content:text,sha256:createHash('sha256').update(text).digest('hex')};
const capsule=await executePublicCatalogueSource(selected);
assert.equal(capsule.receipt.ok,true);
assert.equal(capsule.receipt.state.creative_work_authorities,48);
assert.equal(capsule.receipt.state.canonical_source_units,1065);
assert.equal(capsule.portable.contracts.targetAuthority,false);
const {executePortable}=await import('../coding-estate/everybody/compiler-core.mjs');
assert.deepEqual(executePortable(JSON.parse(JSON.stringify(capsule.portable))).state,capsule.receipt.state);
await assert.rejects(()=>executePublicCatalogueSource({...selected,content:text+' '}),/HASH_HOLD/);
const privateText=text.replace('"private_full_note_text_published": false','"private_full_note_text_published": true');
await assert.rejects(()=>executePublicCatalogueSource({...selected,content:privateText,sha256:createHash('sha256').update(privateText).digest('hex')}),/BOUNDARY_HOLD/);
console.log(JSON.stringify({status:'PASS',checks:7,publicMetadataToOneBody:true,portableJsonReexecution:true,privateCorpus:'EXCLUDED',sourceSha256:selected.sha256}));
